    private fun lookupDynamic(language: String, english: String): String? {
        for (d in dynamic) {
            val match = d.regex.matchEntire(english) ?: continue
            var template = when (language) { "it" -> d.italian; "de" -> d.german; else -> d.spanish }
            for ((i, group) in match.groupValues.drop(1).withIndex()) {
                val value = if (i == d.translateGroup) lookup(language, group) ?: group else group
                template = template.replaceFirst("{}", value)
            }
            return template
        }
        return null
    }

    fun lookup(language: String, english: String): String? = if (english in neutral) english else when (language) {
        "it" -> italian[english] ?: lookupDynamic(language, english)
        "de" -> german[english] ?: lookupDynamic(language, english)
        "es" -> spanish[english] ?: lookupDynamic(language, english)
        else -> null
    }
